#!/usr/bin/env python3
"""Refresh the free-model roster.

Fetches the public OpenRouter catalog (no key needed) and keeps only
models that are genuinely free AND agent-usable:

  - every pricing field is 0 (prompt, completion, and any other meter)
  - supported_parameters includes "tools" (agents need tool calls)
  - output modalities include text and exclude audio
  - the openrouter/free meta-router is kept separately as a fallback,
    not counted as a concrete pick

Ranking is transparent: code-focused models first, then context size,
then reasoning support. Writes data/free-models.json and
data/free-models.md. Run daily (see .github/workflows/refresh.yml).
"""
import json, time, urllib.request
from pathlib import Path

API = "https://openrouter.ai/api/v1/models"
ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
CODE_HINTS = ("code", "coder", "laguna", "devstral")


def is_free(m):
    p = m.get("pricing") or {}
    if not p:
        return False
    for v in p.values():
        if v is None:
            continue
        try:
            if float(v) != 0:
                return False
        except (TypeError, ValueError):
            return False
    return True


def score(m):
    mid = m["id"].lower()
    s = 30 if any(h in mid for h in CODE_HINTS) else 0
    ctx = m.get("context_length") or 0
    s += 15 if ctx >= 1_000_000 else 12 if ctx >= 500_000 else 10 if ctx >= 256_000 else 8 if ctx >= 200_000 else 0
    if "reasoning" in (m.get("supported_parameters") or []):
        s += 5
    return s


def main():
    req = urllib.request.Request(API, headers={"User-Agent": "freetoken-bots/1.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        catalog = json.load(r)["data"]

    picks = []
    for m in catalog:
        if not is_free(m) or m["id"] == "openrouter/free":
            continue
        params = m.get("supported_parameters") or []
        if "tools" not in params:
            continue
        outs = (m.get("architecture") or {}).get("output_modalities") or []
        if "text" not in outs or "audio" in outs:
            continue
        picks.append({
            "id": m["id"],
            "name": m.get("name", m["id"]),
            "context_length": m.get("context_length"),
            "reasoning": "reasoning" in params,
            "score": score(m),
        })
    picks.sort(key=lambda x: (-x["score"], -(x["context_length"] or 0), x["id"]))

    stamp = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    payload = {"refreshed_at": stamp, "source": API,
               "catalog_size": len(catalog), "count": len(picks),
               "fallback": "openrouter/free", "models": picks}
    DATA.mkdir(exist_ok=True)
    (DATA / "free-models.json").write_text(json.dumps(payload, indent=2, ensure_ascii=False))

    lines = [f"<!-- generated by scripts/refresh.py at {stamp} -->",
             "| # | Model | Context | Reasoning | Score |",
             "|---|-------|---------|-----------|-------|"]
    for i, p in enumerate(picks, 1):
        lines.append(f"| {i} | `{p['id']}` | {p['context_length']} | "
                     f"{'yes' if p['reasoning'] else 'no'} | {p['score']} |")
    (DATA / "free-models.md").write_text("\n".join(lines) + "\n")
    print(f"catalog={len(catalog)} free+tools={len(picks)}")


if __name__ == "__main__":
    main()
